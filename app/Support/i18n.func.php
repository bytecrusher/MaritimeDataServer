function mds_t($key, array $replacements = array())
{
    $language = mds_current_language();
    $translations = mds_translations();
    $value = $translations[$language][$key] ?? $key;

    if (!empty($replacements)) {
        $value = vsprintf($value, $replacements);
    }

    return $value;
}

<?php

function mds_supported_languages()
{
    return array('en', 'de');
}

function mds_normalize_language($language)
{
    $language = strtolower(substr((string)$language, 0, 2));
    return in_array($language, mds_supported_languages(), true) ? $language : 'en';
}

function mds_set_current_language($language)
{
    if (session_status() !== PHP_SESSION_ACTIVE) {
        mds_start_session();
    }

    $_SESSION['language'] = mds_normalize_language($language);
}

function mds_set_request_language($language)
{
    $GLOBALS['mds_request_language'] = mds_normalize_language($language);
}

function mds_current_language()
{
    if (!empty($GLOBALS['mds_request_language'])) {
        return mds_normalize_language($GLOBALS['mds_request_language']);
    }

    if (session_status() === PHP_SESSION_ACTIVE && !empty($_SESSION['language'])) {
        return mds_normalize_language($_SESSION['language']);
    }

    if (session_status() === PHP_SESSION_ACTIVE && !empty($_SESSION['userObj']) && class_exists('user')) {
        $userObj = @unserialize($_SESSION['userObj'], ['allowed_classes' => ['user']]);
        if ($userObj instanceof user && method_exists($userObj, 'getLanguage')) {
            return mds_normalize_language($userObj->getLanguage());
        }
    }

    return 'en';
}

